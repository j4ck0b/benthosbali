/* =========================================
   APLICAR TRADUCCIONES
========================================= */

function applyTranslations(lang) {
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    const text =
      translations[lang]?.[key] ||
      translations["es"][key] ||
      key;

    el.innerHTML = text; // ← permite HTML y saltos de línea
  });
}

/* =========================================
   SET LANGUAGE
========================================= */

const LANG_KEY = "lang";

function setLanguage(lang) {
  localStorage.setItem(LANG_KEY, lang);
  applyTranslations(lang);

  const selectedFlag = document.querySelector(`.lang-option[data-lang="${lang}"] img`);
  if (selectedFlag) {
    document.getElementById("current-flag").src = selectedFlag.src;
  }
}

/* =========================================
   CARGAR IDIOMA AL INICIAR
========================================= */

document.addEventListener("DOMContentLoaded", () => {
  const savedLang = localStorage.getItem(LANG_KEY) || "en";
  setLanguage(savedLang);
});
